#!/bin/bash
# =============================================================================
# v2.5 五階段策略 - 一鍵啟動腳本
# =============================================================================
# 用法：在終端機執行 `bash run.sh` 即可
# 這個腳本會自動：
#   1. 提高同時開檔案數的上限（解決 macOS 預設 256 太低的問題）
#   2. 進入腳本所在的資料夾
#   3. 執行 score_v22.py
# =============================================================================

# 提高 ulimit 到 8192（macOS 預設 256，會讓 yfinance 平行下載失敗）
ulimit -n 8192

# 切換到此腳本所在的資料夾（無論從哪裡呼叫都能找到 score_v22.py）
cd "$(dirname "$0")"

# 執行 Python 評分腳本，把所有命令列參數透傳過去
# 例：bash run.sh --no-fetch
python3 score_v22.py "$@"
